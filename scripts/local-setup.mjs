import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { parseEnv } from "node:util";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const target = new URL(".env", root);
const dockerFile = new URL(".env.docker.local", root);
const read = (path) =>
  existsSync(path) ? parseEnv(readFileSync(path, "utf8")) : {};
const current = read(target);
let configuredHost;
if (current.DATABASE_URL) {
  try {
    configuredHost = new URL(current.DATABASE_URL).hostname;
  } catch {
    throw new Error(
      "Invalid DATABASE_URL in local configuration. Correct it privately before running setup.",
    );
  }
}
if (current.DATABASE_DRIVER === "postgres" && !existsSync(dockerFile))
  throw new Error(
    "Local Docker credentials are missing. Restore .env.docker.local before reusing existing volumes; do not silently generate a new password.",
  );
// Never silently replace an existing hosted database configuration.
if (
  configuredHost &&
  !["localhost", "127.0.0.1", "[::1]"].includes(configuredHost)
) {
  throw new Error(
    "Refusing to replace a hosted database configuration. Select the local workspace configuration explicitly first.",
  );
}
const existing = read(dockerFile);
const secret = () => randomBytes(32).toString("hex");
const password = existing.ISOTRACK_LOCAL_DB_PASSWORD ?? secret();
const redisPassword = existing.ISOTRACK_LOCAL_REDIS_PASSWORD ?? secret();
if (!/^[a-f0-9]{64}$/.test(password) || !/^[a-f0-9]{64}$/.test(redisPassword))
  throw new Error(
    "Invalid local Docker credential file; do not regenerate credentials for an existing volume.",
  );
writeFileSync(
  dockerFile,
  `ISOTRACK_LOCAL_DB_PASSWORD=${password}\nISOTRACK_LOCAL_REDIS_PASSWORD=${redisPassword}\n`,
  { mode: 0o600 },
);
const local = current.DATABASE_DRIVER === "postgres";
const config = {
  PORT: "8000",
  NODE_ENV: "development",
  DEPLOYMENT_ENV: "local",
  APP_URL: "http://localhost:8000",
  FRONTEND_URL: "http://localhost:3000",
  DATABASE_DRIVER: "postgres",
  DATABASE_URL: `postgresql://isotrack_local:${password}@127.0.0.1:15432/isotrack_local`,
  UPSTASH_REDIS_URL: `redis://:${redisPassword}@127.0.0.1:16379`,
  JWT_SECRET: local && current.JWT_SECRET ? current.JWT_SECRET : secret(),
  JWT_REFRESH_SECRET:
    local && current.JWT_REFRESH_SECRET ? current.JWT_REFRESH_SECRET : secret(),
  JWT_EXPIRES_IN: "15m",
  JWT_REFRESH_EXPIRES_IN: "7d",
  ACCOUNT_ACTION_SECRET:
    local && current.ACCOUNT_ACTION_SECRET
      ? current.ACCOUNT_ACTION_SECRET
      : secret(),
  DELIVERY_CODE_SECRET:
    local && current.DELIVERY_CODE_SECRET
      ? current.DELIVERY_CODE_SECRET
      : secret(),
  NOTIFICATION_WORKERS_ENABLED: "false",
  RETENTION_ENABLED: "false",
  STRIPE_MODE: "disabled",
  STRIPE_SECRET_KEY: "",
  STRIPE_WEBHOOK_SECRET: "",
  METRICS_TOKEN: "",
  TRUSTED_PROXY_IPS: "",
};
writeFileSync(
  target,
  "# Local Docker development only. Generated by local:setup; do not commit.\n" +
    Object.entries(config)
      .map(([key, value]) => `${key}=${value}`)
      .join("\n") +
    "\n",
  { mode: 0o600 },
);
console.log(
  `Local-only configuration written in ${fileURLToPath(root)}. Credentials were not printed. Run local:up, db:migrate, then dev.`,
);
